var version = "0.5.0"

const help = `claude-codex-usage — Claude・Codexの使用量とリセット日時（Go版）

  usage                アカウント別の利用枠・トークン使用量
  usage-statusline     tmux用の残り利用枠ゲージ
  setup tmux           設定を標準出力へ生成
  borders              AIの返答待ち・承認待ちの枠色を更新
  status               AIセッション一覧
  attention            承認待ち・入力待ち
  watch                ライブ一覧（1〜9で移動、aで絞り込み、qで終了）
  statusline           tmux用のセッション一覧
  jump %ID             指定ペインへ移動
  version              バージョン表示

  --accounts FILE      複数アカウント設定JSON
  --provider NAME      usage-statuslineでcodex / claudeを表示
  --split-providers    setup tmuxでCodex・Claudeを別の行に表示
  --pane-borders       setup tmuxで返答待ちを赤・承認待ちを黄の枠にする
  --width COLUMNS      ゲージの幅（20〜10000）
  --codex-bin PATH      Codex CLIの実行ファイル
  --claude-bin PATH     Claude CLIの実行ファイル
  --demo               サンプルデータ（認証・ネットワーク不要）
  --json               JSONで表示
  --socket NAME        tmux -L NAME
  --client TTY         移動先のtmuxクライアント
  --agent NAME         claude / codex / gemini で絞り込み
  --interval SECONDS   watchの更新間隔（1〜60秒）
  --attention          承認待ち・入力待ちだけ表示
  --bell               watchで状態変化をベル通知
  --compact            セッション数のみ表示

モニターの実行にNode.jsは不要。tmux・ログイン済みの各CLIを使用します。`

type options struct {
	command string
	pos     []string
	values  map[string]string
	bools   map[string]bool
}

func parse(args []string) (options, error) {
	o := options{command: "status", values: map[string]string{}, bools: map[string]bool{}}
	if len(args) > 0 {
		o.command = args[0]
		args = args[1:]
	}
	for i := 0; i < len(args); i++ {
		a := args[i]
		switch a {
		case "--demo", "--json", "--attention", "--bell", "--compact", "--split-providers", "--pane-borders":
			o.bools[a] = true
		case "--accounts", "--provider", "--width", "--codex-bin", "--claude-bin", "--socket", "--client", "--agent", "--interval":
			if i+1 >= len(args) || strings.HasPrefix(args[i+1], "--") {
				return o, fmt.Errorf("%s の値が必要です", a)
			}
			i++
			o.values[a] = args[i]
		default:
			if strings.HasPrefix(a, "-") {
				return o, fmt.Errorf("不明なオプション: %s", usage.Clean(a))
			}
			o.pos = append(o.pos, a)
		}
	}
	if a := o.values["--agent"]; a != "" && a != "claude" && a != "codex" && a != "gemini" {
		return o, errors.New("--agent は claude / codex / gemini を指定してください")
	}
	if p := o.values["--provider"]; p != "" && p != "claude" && p != "codex" {
		return o, errors.New("--provider は codex / claude を指定してください")
	}
	if o.bools["--bell"] && o.command != "watch" {
		return o, errors.New("--bell は watch で使用してください")
	}
	return o, nil
}
func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'" }
func configQuote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(s) + `"`
}

// Capture resolved CLI paths while the interactive shell has the user's PATH.
// tmux's older environment may not include mise/nvm directories.
func resolveCLI(explicit, name string) string {
	if explicit != "" {
		if path, e := exec.LookPath(explicit); e == nil {
			abs, _ := filepath.Abs(path)
			return abs
		}
		return explicit
	}
	if path, e := exec.LookPath(name); e == nil {
		abs, _ := filepath.Abs(path)
		return abs
	}
	home, _ := os.UserHomeDir()
	for _, p := range []string{filepath.Join(home, ".local", "bin", name), filepath.Join("/opt/homebrew/bin", name), filepath.Join("/usr/local/bin", name)} {
		if path, e := exec.LookPath(p); e == nil {
			return path
		}
	}
	return name
}
func config(o options, executable string) (string, error) {
	command := shellQuote(executable)
	accountOption := ""
	if path := o.values["--accounts"]; path != "" {
		abs, e := filepath.Abs(path)
		if e != nil {
			return "", e
		}
		accountOption = " --accounts " + shellQuote(abs)
	}
	for _, provider := range []string{"codex", "claude"} {
		flag := "--" + provider + "-bin"
		path := resolveCLI(o.values[flag], provider)
		accountOption += " " + flag + " " + shellQuote(path)
	}
	gauge := func(provider string) string {
		s := command + " usage-statusline" + accountOption
		if provider != "" {
			s += " --provider " + provider
		}
		if o.bools["--demo"] {
			s += " --demo"
		}
		field := "#(" + s + " --width #{client_width})"
		if o.bools["--pane-borders"] && provider != "claude" {
			borderCommand := command + " borders"
			if socket := o.values["--socket"]; socket != "" {
				borderCommand += " --socket " + shellQuote(socket)
			}
			field += "#(" + borderCommand + ")"
		}
		return configQuote(field)
	}
	count := 2
	provider := ""
	if o.bools["--split-providers"] {
		count = 3
		provider = "codex"
	}
	lines := []string{"# Generated by claude-codex-usage (Go).", fmt.Sprintf("set -g status %d", count), "set -g status-position bottom", "set -g status-interval 2", "set -g status-format[1] " + gauge(provider)}
	if count == 3 {
		lines = append(lines, "set -g status-format[2] "+gauge("claude"))
	}
	if o.bools["--pane-borders"] {
		lines = append(lines, borderConfig()...)
	}
	watch := command + " watch"
	if o.values["--socket"] != "" {
		watch += " --socket " + shellQuote(o.values["--socket"])
	}
	lines = append(lines, "bind-key a display-popup -E -w 90% -h 80% "+configQuote(watch), "# Filled gauge = remaining quota. Reset times use this computer's timezone.", "# Existing status-right (CPU / clock) is preserved. No tmux restart needed.")
	return strings.Join(lines, "\n") + "\n", nil
}
func run(ctx context.Context, args []string) error {
	o, err := parse(args)
	if err != nil {
		return err
	}
	switch o.command {
	case "help", "--help", "-h":
		fmt.Println(help)
		return nil
	case "version", "--version":
		fmt.Println("claude-codex-usage " + version)
		return nil
	}
	if o.command == "setup" {
		if len(o.pos) != 1 || o.pos[0] != "tmux" {
			return errors.New("使い方: setup tmux")
		}
		exe, e := os.Executable()
		if e != nil {
			return e
		}
		s, e := config(o, exe)
		if e == nil {
			fmt.Print(s)
		}
		return e
	}
	if o.command != "jump" && len(o.pos) > 0 {
		return errors.New("余分な引数があります。helpを参照してください")
	}
	if o.command == "borders" {
		if o.bools["--demo"] {
			return errors.New("bordersは--demoと併用できません")
		}
		err := session.RefreshBorders(ctx, o.values["--socket"])
		fmt.Println("")
		return err
	}
	if o.command == "usage" || o.command == "usage-statusline" {
		width := 100
		if v := o.values["--width"]; v != "" {
			width, err = strconv.Atoi(v)
			if err != nil || width < 20 || width > 10000 {
				return errors.New("--widthは20〜10000の整数で指定してください")
			}
		}
		result := usage.Result{}
		if o.bools["--demo"] {
			result = usage.Demo()
		} else {
			accounts, e := usage.LoadAccounts(o.values["--accounts"])
			err = e
			if err == nil {
				readers := usage.Readers{CodexExecutable: resolveCLI(o.values["--codex-bin"], "codex"), ClaudeExecutable: resolveCLI(o.values["--claude-bin"], "claude")}
				if o.command == "usage" {
					result = usage.Collect(ctx, accounts, readers)
				} else {
					result, err = usage.Cached(ctx, accounts, usage.CacheOptions{Fetch: func(ctx context.Context, a []usage.Account) usage.Result { return usage.Collect(ctx, a, readers) }})
				}
			}
			if err != nil {
				if o.command == "usage-statusline" {
					fmt.Println("AI usage 取得不可 · usage コマンドで確認")
					return nil
				}
				return err
			}
		}
		if o.command == "usage-statusline" {
			if result.Loading {
				fmt.Println("AI usage 取得中…")
				return nil
			}
			if provider := o.values["--provider"]; provider != "" {
				selected := []usage.AccountUsage{}
				for _, a := range result.Accounts {
					if a.Provider == provider {
						selected = append(selected, a)
					}
				}
				result.Accounts = selected
				if len(selected) == 0 {
					fmt.Println(provider + " アカウント未設定")
					return nil
				}
			}
			fmt.Println(usage.RenderGauge(result, width, time.Now()))
			return nil
		}
		if o.bools["--json"] {
			encoder := json.NewEncoder(os.Stdout)
			encoder.SetIndent("", "  ")
			if e := encoder.Encode(result); e != nil {
				return e
			}
		} else {
			fmt.Print(usage.RenderUsage(result))
		}
		success := false
		for _, a := range result.Accounts {
			if a.Error == "" {
				success = true
			}
		}
		if !success {
			return errors.New("利用枠を取得できませんでした")
		}
		return nil
	}
	interval := 2.0
	if v := o.values["--interval"]; v != "" {
		interval, err = strconv.ParseFloat(v, 64)
		if err != nil || !(interval >= 1 && interval <= 60) {
			return errors.New("--interval は1〜60秒です")
		}
	}
	so := session.Options{Socket: o.values["--socket"], Client: o.values["--client"], Agent: o.values["--agent"], Attention: o.bools["--attention"] || o.command == "attention", Compact: o.bools["--compact"], Demo: o.bools["--demo"], Bell: o.bools["--bell"], JSON: o.bools["--json"], Interval: time.Duration(interval * float64(time.Second))}
	if o.command == "jump" {
		if so.Demo {
			return errors.New("デモから実際のペインには移動できません")
		}
		if len(o.pos) != 1 {
			return errors.New("使い方: jump %ID")
		}
		if os.Getenv("TMUX") == "" && so.Client == "" {
			return errors.New("tmux内から実行するか --client を指定してください")
		}
		return session.Jump(ctx, o.pos[0], so)
	}
	switch o.command {
	case "status", "attention", "watch", "statusline":
		return session.Run(ctx, o.command, so)
	default:
		return fmt.Errorf("不明なコマンド: %s", usage.Clean(o.command))
	}
}
func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "claude-codex-usage: "+usage.Clean(err.Error()))
		os.Exit(1)
	}
}
