import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { resolve } from 'node:path';
const exec = promisify(execFile);
export const shellQuote = value => `'${String(value).replaceAll("'", "'\\''")}'`;
export async function tmux(args, socket) {
  const result = await exec('tmux', [...(socket ? ['-L', socket] : []), ...args], { timeout: 5000, maxBuffer: 1024 * 1024 });
  return result.stdout;
}
// Print-only integration: loading it is an explicit user action.
export function tmuxConfig(cliPath, nodePath, socket, { accounts, splitProviders = false } = {}) {
  const command = `${shellQuote(nodePath)} ${shellQuote(cliPath)}`;
  const suffix = socket ? ` --socket ${shellQuote(socket)}` : '';
  const quoteConfig = value => `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('$', '\\$')}"`;
  const accountOption = accounts ? ` --accounts ${shellQuote(resolve(accounts))}` : '';
  const gauge = provider => quoteConfig(`#(${command} usage-statusline${accountOption}${provider ? ` --provider ${provider}` : ''} --width #{client_width})`);
  return [
    '# Generated by claude-codex-usage. Review before sourcing.',
    `set -g status ${splitProviders ? 3 : 2}`,
    'set -g status-position bottom',
    'set -g status-interval 2',
    `set -g status-format[1] ${gauge(splitProviders ? 'codex' : undefined)}`,
    ...(splitProviders ? [`set -g status-format[2] ${gauge('claude')}`] : []),
    `bind-key a display-popup -E -w 90% -h 80% ${quoteConfig(`${command} watch${suffix}`)}`,
    '# Filled gauge = used quota; next reset is shown in local time. Existing status-right is preserved.',
    '# In the popup: 1-9 to jump, q to close; jump %ID also accepts a stable pane target.',
  ].join('\n') + '\n';
}
export async function jumpToPane(pane, { socket, client, run = tmux } = {}) {
  if (!/^%\d+$/.test(pane)) throw new Error('移動先は %3 のようなペインIDで指定してください。');
  // switch-client accepts a pane target and switches session, window and pane atomically.
  await run(['switch-client', ...(client ? ['-c', client] : []), '-t', pane], socket);
}
